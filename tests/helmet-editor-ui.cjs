const { _electron: electron } = require('playwright-core');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');

(async () => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'opengrid-helmet-ui-'));
  const env = { ...process.env, OPENGRIDXR_DATA_DIR: dir, OPENGRIDXR_TEST_MODE: '1' };
  delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ executablePath: process.env.OPENGRIDXR_TEST_EXE || require('electron'), args: process.env.OPENGRIDXR_TEST_EXE ? [] : [path.resolve('.')], env });
  try {
    const page = await app.firstWindow(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const ready = () => page.waitForFunction(() => document.querySelector('.helmet-render')?.dataset.rendering === 'false' && document.querySelector('.helmet-render > img')?.complete);
    await page.getByRole('button', { name: 'Helmet', exact: true }).click();
    assert.equal(await page.locator('.helmet-render > img').count(), 0);
    await page.getByRole('switch', { name: 'Show helmet', exact: true }).click();
    await ready();
    assert.equal(await page.locator('.helmet-render > img').getAttribute('data-source'), 'formula-left.png');
    await page.getByRole('group', { name: 'Helmet preview eye' }).getByRole('button', { name: 'Right eye', exact: true }).click();
    await ready();
    assert.equal(await page.locator('.helmet-render > img').getAttribute('data-source'), 'formula-right.png');
    await page.getByRole('textbox', { name: 'Sunstrip text', exact: true }).fill('GRID RACING');
    await ready();
    const mirrored = await page.locator('.helmet-render > img').getAttribute('src');
    assert.equal(await page.locator('.helmet-render').getAttribute('data-mirrored'), 'true');
    await page.getByRole('switch', { name: 'Mirror lettering & graphic', exact: true }).click();
    await ready();
    assert.notEqual(await page.locator('.helmet-render > img').getAttribute('src'), mirrored);
    await page.getByLabel('Sunstrip color', { exact: true }).fill('#bd732e');
    await page.getByRole('spinbutton', { name: 'Sunstrip opacity value', exact: true }).fill('38');
    await ready();
    await page.getByRole('spinbutton', { name: 'Left crop value', exact: true }).fill('15');
    assert.equal(await page.locator('.helmet-render clipPath[id$="-crop"] rect').getAttribute('x'), '120');
    await page.getByRole('switch', { name: 'Use contour in driving', exact: true }).click();
    assert.equal(await page.locator('.helmet-render clipPath[id$="-contour"] polygon').count(), 1);
    await page.getByRole('group', { name: 'Helmet editor section' }).getByRole('button', { name: 'Graphic', exact: true }).click();
    const raster = await page.evaluate(() => {
      const canvas = document.createElement('canvas'); canvas.width = 320; canvas.height = 80;
      const ctx = canvas.getContext('2d'); ctx.fillStyle = '#ffb02e'; ctx.fillRect(0, 0, 320, 80);
      ctx.fillStyle = '#111111'; ctx.font = 'bold 34px sans-serif'; ctx.fillText('YOUR TEAM', 48, 52);
      return canvas.toDataURL('image/png').split(',')[1];
    });
    await page.getByLabel('Upload visor graphic', { exact: true }).setInputFiles({ name: 'logo.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') });
    await page.getByRole('status').filter({ hasText: 'Choose a PNG, JPEG or WebP image.' }).waitFor();
    await page.getByLabel('Upload visor graphic', { exact: true }).setInputFiles({ name: 'logo.png', mimeType: 'image/png', buffer: Buffer.from(raster, 'base64') });
    await page.getByText('Graphic added. It is embedded in this profile and included in exports.').waitFor();
    await ready();
    const graphicRaster = await page.locator('.helmet-render > img').getAttribute('src');
    await page.getByRole('spinbutton', { name: 'Graphic horizontal position value' }).fill('10');
    await ready();
    assert.notEqual(await page.locator('.helmet-render > img').getAttribute('src'), graphicRaster);
    await page.getByRole('button', { name: 'Save profile', exact: true }).click();
    await page.getByRole('button', { name: 'Profile saved', exact: true }).waitFor();
    const state = await page.evaluate(() => window.openGrid.load());
    const saved = state.document.profiles.find(p => p.id === state.document.selectedProfileId);
    assert.equal(saved.helmet.visor.text, 'GRID RACING');
    assert.equal(saved.helmet.visor.opacity, 38);
    assert.equal(saved.helmet.visor.color, '#bd732e');
    assert.equal(saved.helmet.visor.graphicX, 10);
    assert.equal(saved.view.crop.left, 15);
    assert.match(saved.helmet.visor.graphic, /^data:image\/png;base64,/);
    await page.reload();
    await page.getByRole('button', { name: 'Helmet', exact: true }).click();
    await ready();
    assert.equal(await page.getByRole('textbox', { name: 'Sunstrip text', exact: true }).inputValue(), 'GRID RACING');
    await page.getByRole('group', { name: 'Helmet editor section' }).getByRole('button', { name: 'Graphic', exact: true }).click();
    await page.getByRole('button', { name: 'Remove graphic', exact: true }).click();
    assert.equal(await page.getByAltText('Your visor graphic').count(), 0);
    await page.getByRole('group', { name: 'Helmet editor section' }).getByRole('button', { name: 'Sunstrip', exact: true }).click();
    await page.getByRole('switch', { name: 'Upper sunstrip', exact: true }).click();
    await ready();
    assert.equal(await page.locator('.helmet-render').getAttribute('data-visor-enabled'), 'false');
    await page.getByRole('switch', { name: 'Upper sunstrip', exact: true }).click();
    await page.getByRole('switch', { name: 'Show helmet', exact: true }).click();
    assert.equal(await page.locator('.helmet-render > img, [data-testid="visor-band"]').count(), 0);
    await page.getByRole('switch', { name: 'Show helmet', exact: true }).click();
    await page.getByRole('button', { name: 'Fit crop to visor opening', exact: true }).click();
    await page.getByText(/Both eyes fitted with a conservative margin/).waitFor();
    assert.ok((await page.locator('.helmet-render clipPath[id$="-contour"] polygon').getAttribute('points')).split(' ').length > 10);
    assert.ok(Number(await page.getByRole('spinbutton', { name: 'Top crop value', exact: true }).inputValue()) > 0);
    await fs.mkdir('test-results', { recursive: true });
    await page.getByRole('textbox', { name: 'Sunstrip text', exact: true }).fill('OPEN GRID');
    await page.getByRole('button', { name: 'White / red', exact: true }).click();
    await ready();
    await page.locator('.helmet-render').screenshot({ path: 'test-results/helmet-curved-white-red.png' });
    await page.getByRole('button', { name: 'Dark / white', exact: true }).click();
    await ready();
    await page.locator('.helmet-render').screenshot({ path: 'test-results/helmet-curved-dark-white.png' });
    await page.getByRole('group', { name: 'Helmet editor section' }).getByRole('button', { name: 'Visor', exact: true }).click();
    await page.getByLabel('Visor tint color', { exact: true }).fill('#d8a64e');
    await page.getByRole('spinbutton', { name: 'Whole visor tint value', exact: true }).fill('15');
    await page.getByRole('spinbutton', { name: 'Scene contrast value', exact: true }).fill('125');
    await page.getByRole('spinbutton', { name: 'Scene brightness value', exact: true }).fill('110');
    await page.getByRole('spinbutton', { name: 'Scene saturation value', exact: true }).fill('80');
    await ready();
    assert.equal(await page.locator('.helmet-scene-grade').evaluate(el => el.style.filter), 'brightness(1.1) contrast(1.25) saturate(0.8)');
    await page.getByRole('button', { name: 'Save profile', exact: true }).click();
    await page.getByRole('button', { name: 'Profile saved', exact: true }).waitFor();
    const updated = (await page.evaluate(() => window.openGrid.load())).document.profiles.find(p => p.id === saved.id);
    assert.equal(updated.helmet.visorContrast, 125);
    assert.equal(updated.helmet.visorBrightness, 110);
    assert.equal(updated.helmet.visorSaturation, 80);
    assert.equal(updated.helmet.visorTintColor, '#d8a64e');
    await page.screenshot({ path: 'test-results/helmet-studio.png', fullPage: true });
    assert.deepEqual(errors, []);
    console.log('Helmet controls, actual preview geometry, mirrored text, raster upload/removal and off states passed.');
  } finally {
    await app.evaluate(({ BrowserWindow }) => { for (const win of BrowserWindow.getAllWindows()) win.destroy(); }).catch(() => {});
    await app.close();
    await fs.rm(dir, { recursive: true, force: true });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
