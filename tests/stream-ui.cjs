const {_electron:electron}=require('playwright-core');
const fs=require('node:fs/promises'), path=require('node:path'), os=require('node:os'), assert=require('node:assert/strict');
(async()=>{
  const {createDocument}=await import('../src/model.mjs');
  const dir=await fs.mkdtemp(path.join(os.tmpdir(),'opengrid-stream-ui-'));
  const doc=createDocument();doc.profiles[0].stream.preserveFullFrame=true;
  const originalHelmet=structuredClone(doc.profiles[0].helmet), originalMask=structuredClone(doc.profiles[0].mask);
  await fs.writeFile(path.join(dir,'profiles.json'),JSON.stringify(doc));
  const ini=path.join(dir,'Track stream.ini');
  await fs.writeFile(ini,'\ufeff[Preview]\nMode=1\nSmoothingTenths=425\nHorizonTenths=500\nAdaptiveHorizon=1\nPitchTenths=250\nMirror=1\nMirrorLimitTenths=125\nMirrorSoftnessTenths=600\nMirrorStretchTenths=300\nSourceTitle=Old window\n');
  const env={...process.env,OPENGRIDXR_DATA_DIR:dir,OPENGRIDXR_TEST_MODE:'1'};delete env.ELECTRON_RUN_AS_NODE;
  let app;
  try{
    app=await electron.launch({executablePath:process.env.OPENGRIDXR_TEST_EXE||require('electron'),args:process.env.OPENGRIDXR_TEST_EXE?[]:[path.resolve('.')],env,timeout:60000});
    const page=await app.firstWindow();page.setDefaultTimeout(20000);
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Stream',exact:true}).click();
    assert.equal(await page.getByRole('group',{name:'Profile mode',exact:true}).count(),0);
    assert.equal(await page.locator('.mode-switch').count(),0);
    const fullFrame=page.getByRole('switch',{name:'Keep full render area for stream',exact:true});
    assert.equal(await fullFrame.getAttribute('aria-checked'),'true');
    await fullFrame.click();
    assert.equal(await fullFrame.getAttribute('aria-checked'),'false');
    await fullFrame.click();
    const number=name=>page.getByRole('spinbutton',{name:`${name} value`,exact:true});
    assert.equal(await number('Mirror limit').isDisabled(),true);
    await page.getByRole('switch',{name:'Mirrored borders',exact:true}).click();
    await number('Mirror limit').fill('12.5');
    await number('Mirror softness').fill('60');
    await number('Mirror stretch').fill('30');
    await page.getByRole('switch',{name:'Adaptive roll leveling',exact:true}).click();
    await number('Horizon lock').fill('50');
    await number('Pitch stabilization').fill('25');
    await page.getByRole('switch',{name:'Show helmet in stream',exact:true}).click();
    await number('Stream helmet size').fill('175');
    await number('Stream helmet horizontal position').fill('8');
    await number('Stream helmet vertical position').fill('-6');
    await number('Stream helmet opacity').fill('70');
    await page.getByAltText('Stream helmet preview').waitFor();
    await page.waitForFunction(()=>!document.querySelector('.stream-helmet-status'));
    assert.equal(await page.getByAltText('Stream helmet preview').evaluate(el=>getComputedStyle(el).opacity),'0.7');
    await page.getByRole('button',{name:'Save profile',exact:true}).click();
    await page.getByRole('button',{name:'Profile saved',exact:true}).waitFor();
    let saved=(await page.evaluate(()=>window.openGrid.load())).document.profiles[0];
    assert.equal(saved.stream.pitchLock,25);assert.equal(saved.stream.adaptiveHorizon,true);
    assert.equal(saved.stream.preserveFullFrame,true);assert.equal(Object.hasOwn(saved,'mode'),false);
    assert.equal(saved.stream.helmet.scale,175);assert.equal(saved.stream.helmet.offsetY,-6);
    assert.deepEqual(saved.helmet,originalHelmet);assert.deepEqual(saved.mask,originalMask);
    const helmetManifest=JSON.parse(await fs.readFile(path.join(dir,'runtime','OpenGridXR-stream-helmet-iracing.json')));
    assert.equal(helmetManifest.enabled,true);assert.equal(helmetManifest.streamOpacity,70);
    const headsetManifest=JSON.parse(await fs.readFile(path.join(dir,'runtime','OpenGridXR-helmet-iracing.json')));
    assert.equal(headsetManifest.enabled,false);
    await fs.mkdir(path.resolve('test-results'),{recursive:true});
    await page.screenshot({path:path.resolve('test-results/stream-controls.png'),fullPage:true});
    await page.reload();
    await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Stream',exact:true}).click();
    assert.equal(await number('Stream helmet size').inputValue(),'175');
    await page.getByRole('switch',{name:'Show helmet in stream',exact:true}).click();
    assert.equal(await page.getByAltText('Stream helmet preview').count(),0);
    await page.getByRole('button',{name:'Save profile',exact:true}).click();
    await page.getByRole('button',{name:'Profile saved',exact:true}).waitFor();
    assert.equal(JSON.parse(await fs.readFile(path.join(dir,'runtime','OpenGridXR-stream-helmet-iracing.json'))).enabled,false);
    // Real IPC and file decoding; only the native file chooser is replaced.
    await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},ini);
    await page.getByRole('button',{name:'Import steadyXR preset',exact:true}).click();
    await page.getByRole('heading',{name:'steadyXR preset imported',exact:true}).waitFor();
    await page.getByText(/SourceTitle binding skipped/).waitFor();
    assert.equal(await number('Pitch stabilization').inputValue(),'25');
    assert.equal(await number('Mirror limit').inputValue(),'12.5');
    assert.equal((await page.evaluate(()=>window.openGrid.load())).document.profiles.length,2,'Import remains unsaved');
    await page.getByRole('button',{name:'Save profile',exact:true}).click();
    await page.getByRole('button',{name:'Profile saved',exact:true}).waitFor();
    const loaded=(await page.evaluate(()=>window.openGrid.load())).document;
    assert.equal(loaded.profiles.length,3);
    const imported=loaded.profiles.find(p=>p.id===loaded.selectedProfileId);
    assert.equal(imported.name,'Track stream');assert.equal(imported.stream.preserveFullFrame,true);assert.equal(Object.hasOwn(imported,'mode'),false);assert.equal(imported.stream.smoothing,42.5);
    await page.screenshot({path:path.resolve('test-results/stream-import.png'),fullPage:true});
    await assert.rejects(page.evaluate(()=>window.openGrid.importSteadyXr('other')),/supported game/);
    await app.evaluate(({dialog})=>{dialog.showOpenDialog=async()=>({canceled:true,filePaths:[]});});
    assert.equal(await page.evaluate(()=>window.openGrid.importSteadyXr('lmu')),null);
    assert.deepEqual(errors,[]);
    console.log('Stream UI: save/reload, independent helmet and assets, toggle off, native INI import/report/new draft, cancel and validation passed.');
  }finally{
    if(app){await app.evaluate(({BrowserWindow})=>{for(const w of BrowserWindow.getAllWindows())w.destroy();});await app.close();}
    await fs.rm(dir,{recursive:true,force:true});
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
